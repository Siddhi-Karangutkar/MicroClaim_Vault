import { useState, useEffect } from 'react';
import { useParams, useNavigate } from 'react-router-dom';
import { doc, getDoc } from 'firebase/firestore';
import { db } from '../services/firebase';
import { ArrowLeft, FileText, Download, FileImage, ShieldAlert, ShieldCheck, Loader2, Copy, Check } from 'lucide-react';
import { jsPDF } from 'jspdf';

export default function ItemDetails() {
  const { id } = useParams();
  const navigate = useNavigate();
  const [item, setItem] = useState(null);
  const [loading, setLoading] = useState(true);
  
  // Letter state
  const [letterText, setLetterText] = useState("");
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    const fetchItem = async () => {
      try {
        const docRef = doc(db, 'vaultItems', id);
        const docSnap = await getDoc(docRef);
        if (docSnap.exists()) {
          const data = { id: docSnap.id, ...docSnap.data() };
          setItem(data);
          
          // Generate default letter
          const pDate = new Date(data.purchaseDate).toLocaleDateString();
          setLetterText(`Subject: Warranty Claim for ${data.productName}

To Whom It May Concern at ${data.brand},

I am writing to formally request a warranty replacement or repair for my ${data.productName}. 

I purchased this item on ${pDate}. According to your terms, this product is covered under a ${data.warrantyMonths}-month warranty, making this an active and valid claim.

The product has recently stopped functioning as intended under normal use conditions. As this falls within the guaranteed warranty period, I kindly request instructions on how to proceed with a replacement or repair.

I have retained the original proof of purchase (receipt) for verification purposes.

Please contact me at your earliest convenience to resolve this matter.

Sincerely,

[Your Name]
[Your Contact Information]`);

        } else {
          console.error("No such item!");
        }
      } catch (error) {
        console.error("Error fetching item:", error);
      }
      setLoading(false);
    };
    fetchItem();
  }, [id]);

  const generatePDF = () => {
    if (!item) return;
    
    const doc = new jsPDF();
    
    // Header
    doc.setFont("helvetica", "bold");
    doc.setFontSize(22);
    doc.text("Formal Warranty Claim", 105, 20, { align: "center" });
    
    doc.setFontSize(12);
    doc.setFont("helvetica", "normal");
    doc.text(`Date: ${new Date().toLocaleDateString()}`, 20, 40);
    
    // Body from Textarea (which now includes Subject)
    doc.setFont("helvetica", "normal");
    const splitText = doc.splitTextToSize(letterText, 170);
    doc.text(splitText, 20, 55);
    
    // Footer / Metadata
    doc.setFontSize(10);
    doc.setTextColor(150);
    doc.text(`Generated by MicroClaim Vault - ID: ${item.id}`, 20, 280);

    // Save PDF
    doc.save(`Warranty_Claim_${item.brand.replace(/\s+/g, '_')}.pdf`);
  };

  const copyToClipboard = () => {
    navigator.clipboard.writeText(letterText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  if (loading) {
    return (
      <div className="flex items-center justify-center min-h-[50vh]">
        <Loader2 className="w-8 h-8 animate-spin text-neon" />
      </div>
    );
  }

  if (!item) {
    return (
      <div className="text-center py-20">
        <h2 className="text-2xl font-bold mb-4">Item not found</h2>
        <button onClick={() => navigate('/dashboard')} className="text-neon hover:underline">
          Return to Dashboard
        </button>
      </div>
    );
  }

  const isExpired = item.status === 'Expired';
  const Icon = isExpired ? ShieldAlert : ShieldCheck;
  const statusColor = isExpired ? 'text-red-500' : 'text-neon';
  const bgGlow = isExpired ? 'bg-red-500/10' : 'bg-neon/10';

  return (
    <div className="max-w-4xl mx-auto space-y-8 animate-fade-in-up">
      {/* Back Button */}
      <button 
        onClick={() => navigate('/dashboard')}
        className="flex items-center gap-2 text-slate-500 hover:text-white transition-colors"
      >
        <ArrowLeft className="w-4 h-4" /> Back to Vault
      </button>

      <div className="grid grid-cols-1 md:grid-cols-3 gap-8">
        
        {/* Left Col: Details */}
        <div className="md:col-span-2 space-y-6">
          <div className={`glass-card p-8 border-t-4 ${isExpired ? 'border-red-500' : 'border-neon'} relative overflow-hidden`}>
            <div className={`absolute top-0 right-0 w-64 h-64 ${bgGlow} rounded-full blur-3xl -translate-y-1/2 translate-x-1/3 pointer-events-none`}></div>
            
            <div className="relative z-10 flex justify-between items-start">
              <div>
                <p className="text-slate-400 font-medium tracking-widest uppercase text-sm mb-2">{item.brand}</p>
                <h1 className="text-3xl md:text-4xl font-bold">{item.productName}</h1>
              </div>
              <div className={`flex flex-col items-end ${statusColor}`}>
                <Icon className="w-10 h-10 mb-2" />
                <span className="font-bold uppercase tracking-wide">{item.status}</span>
              </div>
            </div>

            <div className="mt-8 grid grid-cols-2 gap-6 pt-6 border-t border-white/10 relative z-10">
              <div>
                <p className="text-sm text-slate-400 mb-1">Purchase Date</p>
                <p className="font-bold text-lg">{new Date(item.purchaseDate).toLocaleDateString()}</p>
              </div>
              <div>
                <p className="text-sm text-slate-400 mb-1">Expiration Date</p>
                <p className={`font-bold text-lg ${isExpired && 'text-red-500'}`}>
                  {new Date(item.expirationDate).toLocaleDateString()}
                </p>
              </div>
              <div>
                <p className="text-sm text-slate-400 mb-1">Warranty Length</p>
                <p className="font-bold text-lg">{item.warrantyMonths} Months</p>
              </div>
              <div>
                <p className="text-sm text-slate-400 mb-1">Price</p>
                <p className="font-bold text-lg">{item.price || 'N/A'}</p>
              </div>
            </div>
          </div>
          
          {/* Claim Letter Editor */}
          <div className="glass-card p-6">
            <h3 className="font-bold text-xl mb-2 flex items-center gap-2">
              <FileText className="w-5 h-5 text-neon" /> 
              Draft Claim Letter
            </h3>
            <p className="text-sm text-slate-400 mb-4">
              Edit the letter below before generating the PDF or copying for email.
            </p>
            <textarea
              className="w-full h-64 bg-slate-100 dark:bg-slate-900/50 border border-slate-300 dark:border-white/10 rounded-lg p-4 text-slate-900 dark:text-slate-200 focus:outline-none focus:border-neon focus:ring-1 focus:ring-neon transition-colors resize-none"
              value={letterText}
              onChange={(e) => setLetterText(e.target.value)}
              disabled={isExpired}
            ></textarea>
            
            <div className="flex gap-4 mt-4">
              <button 
                onClick={generatePDF}
                className={`flex-1 py-3 rounded-xl font-bold text-sm md:text-base hover:scale-[1.02] active:scale-[0.98] transition-all flex items-center justify-center gap-2 ${
                  isExpired 
                    ? 'bg-slate-700 text-slate-400 cursor-not-allowed' 
                    : 'bg-white text-slate-900 shadow-sm'
                }`}
                disabled={isExpired}
              >
                <Download className="w-4 h-4" />
                Download PDF
              </button>
              
              <button 
                onClick={copyToClipboard}
                className={`flex-1 py-3 rounded-xl font-bold text-sm md:text-base hover:scale-[1.02] active:scale-[0.98] transition-all flex items-center justify-center gap-2 ${
                  isExpired 
                    ? 'bg-slate-700 text-slate-400 cursor-not-allowed' 
                    : 'bg-neon text-slate-900 shadow-[0_0_20px_rgba(0,255,204,0.2)]'
                }`}
                disabled={isExpired}
              >
                {copied ? <Check className="w-4 h-4" /> : <Copy className="w-4 h-4" />}
                {copied ? 'Copied!' : 'Copy for Email'}
              </button>
            </div>
          </div>

        </div>

        {/* Right Col: Actions & Receipt */}
        <div className="space-y-6">
          <div className="glass-card p-6">
            <h3 className="font-bold text-xl mb-4 flex items-center gap-2">
              <FileImage className="w-5 h-5 text-neon" /> 
              Proof of Purchase
            </h3>
            {item.receiptUrl ? (
              <a 
                href={item.receiptUrl} 
                target="_blank" 
                rel="noreferrer"
                className="w-full block py-3 bg-white/5 hover:bg-white/10 border border-white/10 rounded-xl font-medium text-center transition-colors"
              >
                View Original Receipt
              </a>
            ) : (
              <p className="text-sm text-slate-400 text-center py-4">No receipt image stored.</p>
            )}
          </div>
        </div>

      </div>
    </div>
  );
}
